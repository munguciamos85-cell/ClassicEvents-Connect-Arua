insert into storage.buckets (id,name,public) values ('provider-media','provider-media',true)
on conflict (id) do update set public=true;

drop policy if exists provider_media_public_read on storage.objects;
drop policy if exists provider_media_authenticated_upload on storage.objects;
drop policy if exists provider_media_owner_update on storage.objects;
drop policy if exists provider_media_owner_delete on storage.objects;
drop policy if exists provider_media_admin_delete on storage.objects;

create policy provider_media_public_read on storage.objects for select using (bucket_id='provider-media');
create policy provider_media_authenticated_upload on storage.objects for insert to authenticated
with check (bucket_id='provider-media' and (name like auth.uid()::text || '/%'));
create policy provider_media_owner_update on storage.objects for update to authenticated
using (bucket_id='provider-media' and owner_id=auth.uid()::text)
with check (bucket_id='provider-media' and owner_id=auth.uid()::text);
create policy provider_media_owner_delete on storage.objects for delete to authenticated
using (bucket_id='provider-media' and owner_id=auth.uid()::text);
create policy provider_media_admin_delete on storage.objects for delete to authenticated
using (bucket_id='provider-media' and public.is_admin_or_moderator());

