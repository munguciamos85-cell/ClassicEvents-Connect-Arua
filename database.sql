-- Drop/recreate policies so the script can be safely rerun.
do $$ declare r record; begin
  for r in select schemaname,tablename,policyname from pg_policies where schemaname='public' and tablename in ('profiles','providers','project_media','events','bookings','reviews','messages','notifications','user_roles','site_settings','audit_log') loop
    execute format('drop policy if exists %I on %I.%I',r.policyname,r.schemaname,r.tablename);
  end loop;
end $$;

